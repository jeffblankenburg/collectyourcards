import { Catalog, Column, Table } from "./catalog.js";
import { TARGET_SCHEMA } from "./config.js";
import { AddConstraint, Resolver, resolveFk, SyntheticFk } from "./transform.js";

const q = (id: string) => `"${id}"`;
export const qt = (t: string) => `${q(TARGET_SCHEMA)}.${q(t)}`;

// SQL Server -> Postgres type map. Throws on anything unmapped so we never
// silently mis-translate a column. Per-column overrides live in transform.ts and
// are applied by colType() below.
export function pgType(col: Column): string {
  const t = col.sqlType;
  switch (t) {
    case "bit": return "boolean";
    case "tinyint": return "smallint";
    case "smallint": return "smallint";
    case "int": return "integer";
    case "bigint": return "bigint";
    case "decimal":
    case "numeric": return `numeric(${col.precision ?? 38},${col.scale ?? 0})`;
    case "money": return "numeric(19,4)";
    case "smallmoney": return "numeric(10,4)";
    case "float": return "double precision";
    case "real": return "real";
    case "date": return "date";
    case "datetime":
    case "datetime2":
    case "smalldatetime":
    case "datetimeoffset": return "timestamptz";
    case "time": return "time";
    case "char":
    case "nchar":
    case "varchar":
    case "nvarchar":
      return col.maxLen === -1 || col.maxLen === null ? "text" : `varchar(${col.maxLen})`;
    case "text":
    case "ntext": return "text";
    case "uniqueidentifier": return "uuid";
    case "binary":
    case "varbinary":
    case "image": return "bytea";
    case "xml": return "text";
    default:
      throw new Error(`Unmapped SQL Server type "${t}" (column ${col.name})`);
  }
}

// Effective PG type for a column, honoring transform overrides (grade, money, …).
function colType(table: string, col: Column, r: Resolver): string {
  return r.pgTypeFor(table, col) ?? pgType(col);
}

// Build the target schema. For a throwaway schema (legacy) we drop+recreate the
// whole schema. For `public` we MUST NOT drop the schema (it holds extensions,
// grants, and future Prisma objects) — we drop only the tables we own, in reverse
// dependency order, with CASCADE to clear our own FKs.
export function buildSchemaSql(cat: Catalog): string[] {
  if (TARGET_SCHEMA === "public") {
    const drops = [...cat.order].reverse().map((n) => `DROP TABLE IF EXISTS ${qt(n)} CASCADE;`);
    return [`CREATE SCHEMA IF NOT EXISTS ${q(TARGET_SCHEMA)};`, ...drops];
  }
  return [
    `DROP SCHEMA IF EXISTS ${q(TARGET_SCHEMA)} CASCADE;`,
    `CREATE SCHEMA ${q(TARGET_SCHEMA)};`,
  ];
}

// CREATE TABLE with transform applied: dropped/computed columns excluded, target
// names + type overrides emitted, PK resolved through the rename map.
export function createTableSql(t: Table, r: Resolver): string {
  const lines: string[] = [];
  for (const entry of r.colPlan(t)) {
    const col = entry.col;
    let def = `  ${q(entry.targetName)} ${colType(t.name, col, r)}`;
    if (col.isIdentity) def += " GENERATED BY DEFAULT AS IDENTITY"; // preserve original ids, auto-generate future
    if (!col.nullable) def += " NOT NULL";
    lines.push(def);
  }
  if (t.pk.length) lines.push(`  PRIMARY KEY (${t.pk.map((c) => q(r.target(t.name, c))).join(", ")})`);
  return `CREATE TABLE ${qt(t.name)} (\n${lines.join(",\n")}\n);`;
}

// FK constraints are added AFTER bulk load. Child + parent columns are resolved
// to their target (renamed) names.
export function addFkSql(t: Table, r: Resolver): { name: string; sql: string }[] {
  return t.fks.map((fk) => {
    const { childCols, parentCols } = resolveFk(r, fk);
    return {
      name: fk.name,
      sql:
        `ALTER TABLE ${qt(fk.childTable)} ADD CONSTRAINT ${q(fk.name)} ` +
        `FOREIGN KEY (${childCols.map(q).join(", ")}) ` +
        `REFERENCES ${qt(fk.parentTable)} (${parentCols.map(q).join(", ")});`,
    };
  });
}

// Synthetic FK (missing in source) — same shape as a real FK, named by its id.
export function syntheticFkSql(fk: SyntheticFk, r: Resolver): { name: string; sql: string } {
  const cc = fk.childCols.map((c) => r.target(fk.childTable, c));
  const pc = fk.parentCols.map((c) => r.target(fk.parentTable, c));
  return {
    name: fk.id,
    sql:
      `ALTER TABLE ${qt(fk.childTable)} ADD CONSTRAINT ${q(fk.id.replace(/\./g, "_"))} ` +
      `FOREIGN KEY (${cc.map(q).join(", ")}) REFERENCES ${qt(fk.parentTable)} (${pc.map(q).join(", ")});`,
  };
}

// UNIQUE / NOT NULL constraints we add on top of the source (names resolved).
export function addConstraintSql(ac: AddConstraint, r: Resolver): string {
  const cols = ac.columns.map((c) => r.target(ac.table, c));
  if (ac.kind === "unique") {
    return `ALTER TABLE ${qt(ac.table)} ADD CONSTRAINT ${q(ac.id.replace(/\./g, "_"))} UNIQUE (${cols.map(q).join(", ")});`;
  }
  // notnull (single column)
  return `ALTER TABLE ${qt(ac.table)} ALTER COLUMN ${q(cols[0])} SET NOT NULL;`;
}

// After loading explicit identity values, bump the identity sequence past MAX(id).
export function identityResetSql(t: Table, r: Resolver): string | null {
  const idCol = t.columns.find((c) => c.isIdentity);
  if (!idCol) return null;
  const target = r.target(t.name, idCol.name);
  return (
    `SELECT setval(pg_get_serial_sequence('"${TARGET_SCHEMA}"."${t.name}"', '${target}'), ` +
    `GREATEST((SELECT COALESCE(MAX(${q(target)}), 0) FROM ${qt(t.name)}), 1));`
  );
}
