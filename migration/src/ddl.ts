import { Column, Table } from "./catalog.js";
import { TARGET_SCHEMA } from "./config.js";

const q = (id: string) => `"${id}"`;
export const qt = (t: string) => `${q(TARGET_SCHEMA)}.${q(t)}`;

// SQL Server -> Postgres type map. Throws on anything unmapped so we never
// silently mis-translate a column.
export function pgType(col: Column): string {
  const t = col.sqlType;
  switch (t) {
    case "bit": return "boolean";
    case "tinyint": return "smallint";
    case "smallint": return "smallint";
    case "int": return "integer";
    case "bigint": return "bigint";
    case "decimal":
    case "numeric": return `numeric(${col.precision ?? 38},${col.scale ?? 0})`;
    case "money": return "numeric(19,4)";
    case "smallmoney": return "numeric(10,4)";
    case "float": return "double precision";
    case "real": return "real";
    case "date": return "date";
    case "datetime":
    case "datetime2":
    case "smalldatetime":
    case "datetimeoffset": return "timestamptz";
    case "time": return "time";
    case "char":
    case "nchar":
    case "varchar":
    case "nvarchar":
      return col.maxLen === -1 || col.maxLen === null ? "text" : `varchar(${col.maxLen})`;
    case "text":
    case "ntext": return "text";
    case "uniqueidentifier": return "uuid";
    case "binary":
    case "varbinary":
    case "image": return "bytea";
    case "xml": return "text";
    default:
      throw new Error(`Unmapped SQL Server type "${t}" (column ${col.name})`);
  }
}

export function createSchemaSql(): string[] {
  return [
    `DROP SCHEMA IF EXISTS ${q(TARGET_SCHEMA)} CASCADE;`,
    `CREATE SCHEMA ${q(TARGET_SCHEMA)};`,
  ];
}

export function createTableSql(t: Table): string {
  const lines: string[] = [];
  for (const col of [...t.columns].sort((a, b) => a.ordinal - b.ordinal)) {
    let def = `  ${q(col.name)} ${pgType(col)}`;
    // Preserve original identity values now, auto-generate for future inserts.
    if (col.isIdentity) def += " GENERATED BY DEFAULT AS IDENTITY";
    // Replicate NOT NULL for fidelity (source data already satisfies it).
    if (!col.nullable) def += " NOT NULL";
    lines.push(def);
  }
  if (t.pk.length) lines.push(`  PRIMARY KEY (${t.pk.map(q).join(", ")})`);
  return `CREATE TABLE ${qt(t.name)} (\n${lines.join(",\n")}\n);`;
}

// FK constraints are added AFTER bulk load (Postgres validates on ADD), which
// dodges cycle/order problems and is far faster than per-row checks during COPY.
export function addFkSql(t: Table): { name: string; sql: string }[] {
  return t.fks.map((fk) => ({
    name: fk.name,
    sql:
      `ALTER TABLE ${qt(fk.childTable)} ADD CONSTRAINT ${q(fk.name)} ` +
      `FOREIGN KEY (${fk.childCols.map(q).join(", ")}) ` +
      `REFERENCES ${qt(fk.parentTable)} (${fk.parentCols.map(q).join(", ")});`,
  }));
}

// After loading explicit identity values, bump the identity sequence past MAX(id)
// so future app inserts don't collide.
export function identityResetSql(t: Table): string | null {
  const idCol = t.columns.find((c) => c.isIdentity);
  if (!idCol) return null;
  // pg_get_serial_sequence lower-cases unquoted identifiers, so quote the
  // schema-qualified table name (camelCase tables like "userSession" need it).
  return (
    `SELECT setval(pg_get_serial_sequence('"${TARGET_SCHEMA}"."${t.name}"', '${idCol.name}'), ` +
    `GREATEST((SELECT COALESCE(MAX(${q(idCol.name)}), 0) FROM ${qt(t.name)}), 1));`
  );
}
